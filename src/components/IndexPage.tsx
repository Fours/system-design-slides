import { useEffect } from "react";
import { Link } from "react-router";
import { fetchIndex } from "../lib/api";
import { useFetch } from "../lib/useFetch";

/** Route: / — every deck listed in index.json. */
export function IndexPage() {
  const state = useFetch("index", fetchIndex);

  useEffect(() => { document.title = "System Design Walkthroughs"; }, []);

  return (
    <main id="index">
      <header>
        <h1>System Design Walkthroughs</h1>
        <p>Each deck answers one “Design X.” interview question, built up one component at a time.</p>
      </header>
      {state.status === "loading" && <p className="status">Loading…</p>}
      {state.status === "error" && <p className="status">Couldn't load the deck list: {state.error.message}</p>}
      {state.status === "ok" && (
        <ul className="deck-list">
          {state.data.decks.map((d) => (
            <li key={d.slug}>
              <Link to={`/${d.slug}`} className="deck-card">
                <span className="deck-head">
                  <span className="deck-logo">
                    <img src={`logos/${d.slug}.svg`} alt="" onError={(e) => { e.currentTarget.hidden = true; }} />
                  </span>
                  <span className="deck-head-text">
                    <span className="deck-title">{d.title}</span>
                    {/* Looks like a button; the whole card is the link. */}
                    <span className="deck-cta" aria-hidden="true">View <span className="deck-cta-arrow">→</span></span>
                  </span>
                </span>
                {/* Generated by `npm run thumbnails`; hidden if a deck has none yet. */}
                <img className="deck-thumb" src={`thumbnails/${d.slug}.webp`} alt={`Final ${d.title} architecture diagram`}
                  loading="lazy" onError={(e) => { e.currentTarget.hidden = true; }} />
                <span className="deck-description">{d.description}</span>
              </Link>
            </li>
          ))}
        </ul>
      )}
    </main>
  );
}
