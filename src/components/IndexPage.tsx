import { useEffect } from "react";
import { Link, useLocation } from "react-router";
import { fetchIndex } from "../lib/api";
import { useFetch } from "../lib/useFetch";
import type { DeckIndexEntry, DeckIndexSection } from "../types";

/** Route: / — every section of index.json, each with its decks. */
export function IndexPage() {
  const state = useFetch("index", fetchIndex);

  useEffect(() => { document.title = "System Design Walkthroughs"; }, []);

  return (
    <main id="index">
      {state.status === "loading" && <p className="status">Loading…</p>}
      {state.status === "error" && <p className="status">Couldn't load the deck list: {state.error.message}</p>}
      {state.status === "ok" && state.data.sections.map((s, i) => <IndexSection key={s.id} section={s} first={i === 0} />)}
    </main>
  );
}

/** One headed group of deck cards. The first section's header is the page's h1. */
function IndexSection({ section, first }: { section: DeckIndexSection; first: boolean }) {
  const Heading = first ? "h1" : "h2";
  return (
    <section id={section.id} className="index-section" aria-labelledby={`${section.id}-title`}>
      <header>
        <Heading id={`${section.id}-title`}>{section.title}</Heading>
        <p>{section.description}</p>
      </header>
      {section.decks.length === 0 ? (
        <p className="deck-empty">Coming soon.</p>
      ) : (
        <ul className="deck-list">
          {section.decks.map((d) => <DeckCard key={d.slug} deck={d} />)}
        </ul>
      )}
    </section>
  );
}

function DeckCard({ deck: d }: { deck: DeckIndexEntry }) {
  const { search } = useLocation(); // keep ?anim= etc. when opening a deck
  return (
    <li>
      <Link to={{ pathname: `/${d.slug}`, search }} className="deck-card">
        <span className="deck-head">
          <span className="deck-logo">
            <img src={`logos/${d.slug}.svg`} alt="" onError={(e) => { e.currentTarget.hidden = true; }} />
          </span>
          <span className="deck-head-text">
            <span className="deck-title">{d.title}</span>
            {/* Looks like a button; the whole card is the link. */}
            <span className="deck-cta" aria-hidden="true">View <span className="deck-cta-arrow">→</span></span>
          </span>
        </span>
        {/* Generated by `npm run thumbnails`; hidden if a deck has none yet. */}
        <img className="deck-thumb" src={`thumbnails/${d.slug}.webp`} alt={`Final ${d.title} architecture diagram`}
          loading="lazy" onError={(e) => { e.currentTarget.hidden = true; }} />
        <span className="deck-description">{d.description}</span>
      </Link>
    </li>
  );
}
